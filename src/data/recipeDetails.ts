/** 조리법과 쓰는 도구로 정해지는 준비 조건 */
function basePrerequisites(recipe: Recipe): string[] {
  const style = collaborationOf(recipe);
  if (style === 'debate') return ['쓰는 AI 채팅 하나 (무료 웹 채팅도 됩니다)'];
  if (style === 'agent-team') {
    return [ENGINE_PREP['claude-code']!, '에이전트 팀 켜기: zip에 든 .claude/settings.json 적용 (실험 기능)'];
  }
  const list: string[] = [];
  for (const card of recipe.cards) {
    const item = ENGINE_PREP[card.preferredEngine];
    if (item && !list.includes(item)) list.push(item);
  }
  return [...list, '에이전트 파일을 넣을 프로젝트 폴더'];
}

/** 기본 레시피에 학습 정보를 입힌다. 보완 내용이 없는 레시피는 그대로 돌려준다. */
export function withDetails(recipe: Recipe): Recipe {
  const detail = DETAILS[recipe.id];
  if (!detail) return recipe;
  const cards = recipe.cards.map((card) => {
    const spec = detail.cards[card.name];
    if (!spec) return card;
    const [deliverables, criteria, inputs, boundaries] = spec;
    return {
      ...card,
      deliverables: deliverables.map((name, index) => ({ id: `${card.id}-out${index + 1}`, name })),
      completionCriteria: criteria,
      ...(inputs ? { requiredInputs: inputs } : {}),
      ...(boundaries ? { boundaries } : {}),
    };
  });
  const byId = new Map(cards.map((card) => [card.id, card]));
  return {
    ...recipe,
    learningObjective: detail.goal,
    ...(detail.task ? { sampleTask: detail.task } : {}),
    successCriteria: detail.success,
    prerequisites: [...basePrerequisites(recipe), ...(detail.prep ?? [])],
    verification: [...(detail.checks ?? []), FILE_CHECK],
    cards,
    // 넘겨주기는 보내는 역할의 산출물을 모두 넘기는 것으로 한다
    handoffs: recipe.handoffs.map((handoff) => {
      const ids = (byId.get(handoff.from)?.deliverables ?? []).map((item) => item.id);
      return ids.length > 0 ? { ...handoff, deliverableIds: ids } : handoff;
    }),
  };
}

